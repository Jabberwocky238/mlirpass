/// ⭐ The agx table (Mesa's asahi genxml, generated by tools/apple/agxgen).
pub const AGX: Layouts<'_> = Layouts(AGX_ITEMS);

/// ⭐ A register type of a virtual USC instruction's values: `!agx.r<elem>` a GPR (a thread each), `!agx.u<elem>` a
/// uniform (the base, the parameters).
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum AgxType<'e> {
    R(&'e str),
    U(&'e str),
}

impl<'a> From<AgxType<'_>> for Type<'a> {
    fn from(r: AgxType<'_>) -> Self {
        let (name, elem) = match r {
            AgxType::R(e) => ("agx.r", e),
            AgxType::U(e) => ("agx.u", e),
        };
        RegType { name, elem }.into()
    }
}

impl<'t> TryFrom<&'t Type<'_>> for AgxType<'t> {
    type Error = Error;

    fn try_from(t: &'t Type<'_>) -> Result<AgxType<'t>, Error> {
        match RegType::try_from(t)? {
            RegType { name: "agx.r", elem } => Ok(AgxType::R(elem)),
            RegType { name: "agx.u", elem } => Ok(AgxType::U(elem)),
            _ => Err(Error(format!("{t} is not a agx register"))),
        }
    }
}

/// ⭐ The `agx` dialect: load it with `MlirOpt::load(AgxDialect)`.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
pub struct AgxDialect;

impl mlirformat::Dialect for AgxDialect {
    fn namespace(&self) -> &'static str {
        "agx"
    }

    fn ops(&self) -> Vec<mlirformat::Template> {
        [StructOps.ops(), UscOps.ops(), PseudoOps.ops(), G16Ops.ops()].concat()
    }

    fn op_infos(&self) -> Vec<mlirformat::OpInfo> {
        OpRows::of(&self.ops(), &[("agx.usc.input", &["uniform"]), ("agx.kernel", &["sym_name", "stage", "params", "gprs", "align"])])
    }
}

/// `agx.usc.input {uniform}`: uniform half `uniform` on, as the USC Uniform word loads it (the base, the
/// parameters); agx-regalloc keeps the value there and takes the op out.
#[mlirformat::mlir::op("agx.usc.input", format = "attr-dict `->` type($result)", results(result))]
pub struct UscInput<'a> {
    #[attr(int = "i64")]
    pub uniform: i64,
    pub result: Type<'a>,
}

/// ⭐ `agx.kernel @k {stage, params, gprs, align} {...}`: one shader's USC instructions, in order, and what the
/// driver needs to run it: its `params` (32-bit uniforms after the 64-bit base), its 16-bit GPR halves (USC
/// Registers), its alignment (AGX_CODE_ALIGN).
#[mlirformat::mlir::op("agx.kernel", format = "$sym_name attr-dict-with-keyword $body")]
pub struct AgxKernel<'a> {
    #[attr(symbol)]
    pub sym_name: Attribute<'a>,
    pub stage: Option<ShaderStage>,
    pub params: Option<u32>,
    pub gprs: Option<u32>,
    pub align: Option<u64>,
    pub body: Region<'a>,
}

