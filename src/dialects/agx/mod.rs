//! AGX (Apple M1 / M2, G13 / G14) as MLIR: the `agx` dialect.
//!
//! ```text
//!   agx.<struct>   a struct of Mesa's asahi genxml: a word of a VDM / CDM control stream, PPP state, a texture /
//!                  sampler / PBE descriptor, a USC word                                      ⇒ its bytes
//!   agx.usc.<name> a USC (shader) instruction of Mesa's AGX2 model, by its fields          ⇒ its bytes ([`Usc`])
//! ```
//!
//! An op carries its fields as attributes (`agx.cdm_launch_word_0 {uniform_register_count = 64, mode = 1}`), named
//! as Mesa's C names them; an absent field is gen_pack.py's default, an `exact` one is not settable. Their layouts
//! are [`AGX`] (generated by tools/agxgen from data/apple/cmdbuf.xml) and `Layouts::pack` packs them;
//! [`PackItem::num`](crate::PackItem) is the struct's length in bytes.
//!
//!   agx.g16.<form> an Apple G16 (M4) instruction, by its fields                         ⇒ its bytes ([`G16`])
//!   agx.kernel     one shader's USC (or G16) instructions; agx.usc.input: what a thread starts with in a uniform
//!
//! In an `image.stream {cdm}` / `{vdm}` they are a control stream: `agx-end` ends it, `agx-layout` places it.

