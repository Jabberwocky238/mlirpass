//! ⭐ RDNA2 (GFX10.3; Radeon 610M of Ryzen 9000 HX, gfx1036) as MLIR: the `rdna2` dialect.
//!
//! ```text
//!   rdna2.isa.*   a shader instruction (Mesa ACO's GFX10 opcodes), operands in LLVM syntax ⇒ its dwords ([`Rdna2Isa`])
//!   rdna2.kernel  one shader's instructions; rdna2.isa.input: what a wave starts with in a register
//!   rdna2.reg.*   a register's value (Mesa's register database, by MMIO byte offset)   ⇒ one dword
//!   rdna2.pkt.*   a dword of a PM4 packet that has fields (pkt3.json)                  ⇒ one dword
//!   rdna2.pm4.*   a PM4 type-3 packet (sid.h's opcodes), its body as dwords             ⇒ header + body ([`Pm4`])
//! ```
//!
//! A register op carries its fields as attributes (`rdna2.reg.cb_blend0_control {color_srcblend = 1, enable = 1}`);
//! one without fields has `value`. Their layouts are [`RDNA2`] (generated by tools/rdna2gen from data/amd/*.json).
//! In an `image.stream` they are an indirect buffer: `rdna2-pm4` and `rdna2-pad` shape it, [`Pm4::pack`] packs each
//! op.
//!
//! ```text
//!   rdna2.kernel @k {stage = "compute", params = 2, sgprs = 12, vgprs = 6} {   one shader's instructions, in order
//!     rdna2.isa.valu {op = "v_add_u32", dst = "v1", src0 = "v1", src1 = "v0"}  an instruction (registers allocated)
//!   }
//! ```
//!
