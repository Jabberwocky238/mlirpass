#!/usr/bin/env python3
"""data/amd/gfx10-opcodes.json (Mesa ACO's GFX10 instructions, dumped by rdna2_opcodes_dump.py) ⇒
src/dialects/rdna2/opcodes.gen.rs: `Opcode` (every instruction, its format, GFX10 opcode and mnemonic) and `HASHES`
(the mnemonics' FNV-1a hashes, sorted: `Opcode::try_from(&str)` searches integers, then compares one name).
`--check`: fail when the file is stale."""
import json, os, sys

root = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
insts = json.load(open(os.path.join(root, 'data/amd/gfx10-opcodes.json')))
FORMATS = {'SOP1', 'SOP2', 'SOPK', 'SOPP', 'SOPC', 'SMEM', 'DS', 'FLAT', 'GLOBAL', 'SCRATCH', 'VOP1', 'VOP2', 'VOPC',
           'VOP3', 'VOP3P', 'MUBUF', 'MTBUF', 'MIMG', 'EXP', 'VINTRP'}


def camel(name):
    return ''.join(w[:1].upper() + w[1:].lower() for w in name.split('_'))


def fmt(f):
    assert f in FORMATS, f
    return f[:1] + f[1:].lower()


def fnv1a(s):
    h = 0xcbf29ce484222325
    for b in s.encode():
        h = ((h ^ b) * 0x100000001b3) & 0xffffffffffffffff
    return h


out = ['// Generated by scripts/rdna2_opcodes.py from data/amd/gfx10-opcodes.json (Mesa ACO); do not edit.\n\n'
       'use super::Format;\n\n']
out.append('/// Every instruction GFX10 encodes (Mesa ACO\'s table), named as ACO names it; [`Opcode::format`] and\n'
           '/// [`Opcode::code`] are what it encodes as.\n'
           '#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash, PartialOrd, Ord)]\npub enum Opcode {\n')
out += [f'    {camel(i["name"])},\n' for i in insts]
out.append('}\n\nimpl Opcode {\n    /// Its encoding family.\n    pub const fn format(self) -> Format {\n        match self {\n')
out += [f'            Self::{camel(i["name"])} => Format::{fmt(i["format"])},\n' for i in insts]
out.append('        }\n    }\n\n    /// Its GFX10 opcode within the format.\n    pub const fn code(self) -> u32 {\n        match self {\n')
out += [f'            Self::{camel(i["name"])} => {i["opcode"]:#x},\n' for i in insts]
out.append('        }\n    }\n\n    /// Its mnemonic (ACO\'s name).\n    pub const fn name(self) -> &\'static str {\n        match self {\n')
out += [f'            Self::{camel(i["name"])} => "{i["name"]}",\n' for i in insts]
out.append('        }\n    }\n}\n\n/// Every instruction by the FNV-1a hash of its mnemonic, sorted (for [`Opcode`]\'s `TryFrom<&str>`: a search of\n'
           '/// integers, then one comparison of the name).\npub const HASHES: &[(u64, Opcode)] = &[\n')
hashed = sorted((fnv1a(i['name']), i['name']) for i in insts)
assert all(a[0] != b[0] for a, b in zip(hashed, hashed[1:])), 'two mnemonics with one hash'
out += [f'    ({h:#018x}, Opcode::{camel(n)}),\n' for h, n in hashed]
out.append('];\n')
text = ''.join(out)
path = os.path.join(root, 'src/dialects/rdna2/opcodes.gen.rs')
if '--check' in sys.argv:
    sys.exit(0 if open(path).read() == text else 'stale: ' + path)
open(path, 'w').write(text)
print(len(insts), 'instructions')
