#!/usr/bin/env python3
"""Generates src/registry.gen.rs: `Passes::add_upstream` (and `Passes::upstream()`), registering
every `#[pass]` of the crate.

Each pass is registered under the `cfg`s of the `mod` declarations leading from `src/lib.rs` to
its file (`passes/mod.rs`: `#[cfg(feature = "dialect.scf")] mod scf;`, `passes/scf/mod.rs`:
`#[cfg(feature = "target.spirv")] mod convert_scf_to_spirv;`), so a pass is registered exactly
when it is compiled. Its type is the struct after the attribute, or for a `fn` pass the `ty = ..`
it names (default: the fn's name in CamelCase), re-exported at the crate root.

    python3 scripts/registry.py           # rewrite src/registry.gen.rs
    python3 scripts/registry.py --check   # fail if it is out of date
"""

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "src"
OUT = SRC / "registry.gen.rs"

# A `mod` declaration and the attributes right above it.
MOD = re.compile(r"((?:^[ \t]*#\[[^\n]*\]\n)*)^[ \t]*(?:pub(?:\([^)]*\))? )?mod (\w+);", re.M)
CFG = re.compile(r"#\[cfg\((.*)\)\]")
PATH = re.compile(r'#\[path = "([^"]+)"\]')
# `#[pass("name", ..)]` (or `#[crate::pass(..)]`), then doc comments / attributes, then the item.
PASS = re.compile(r'^#\[(?:crate::)?pass\("([^"]+)"(.*)\)\]\n(?:[ \t]*(?:///|#\[)[^\n]*\n)*pub (fn|struct) (\w+)', re.M)


def camel(snake: str) -> str:
    return "".join(w[:1].upper() + w[1:] for w in snake.split("_"))


def children(file: Path):
    """The module files `file` declares, each with the cfgs on its declaration."""
    text = file.read_text()
    # `foo.rs` and `foo/mod.rs` both keep their submodules in `foo/`; `lib.rs` in `src/`.
    base = file.parent if file.name in ("mod.rs", "lib.rs") else file.with_suffix("")
    for m in MOD.finditer(text):
        attrs, name = m.group(1), m.group(2)
        path = PATH.search(attrs)
        if path:
            target = base / path.group(1) if file.name in ("mod.rs", "lib.rs") else file.parent / path.group(1)
        elif (base / f"{name}.rs").exists():
            target = base / f"{name}.rs"
        else:
            target = base / name / "mod.rs"
        if target.exists():
            yield target, CFG.findall(attrs)


def walk():
    """Every module file reachable from lib.rs, with the cfgs leading to it."""
    todo = [(SRC / "lib.rs", [])]
    while todo:
        file, cfgs = todo.pop()
        yield file, cfgs
        for child, own in children(file):
            todo.append((child, cfgs + own))


def passes():
    for file, cfgs in walk():
        for m in PASS.finditer(file.read_text()):
            name, args, kind, ident = m.groups()
            ty = re.search(r"\bty = (\w+)", args)
            yield file.relative_to(SRC).as_posix(), name, ty.group(1) if ty else (camel(ident) if kind == "fn" else ident), cfgs


def cfg(cfgs):
    if not cfgs:
        return None
    return cfgs[0] if len(cfgs) == 1 else "all(" + ", ".join(cfgs) + ")"


def render():
    rows = sorted(passes())
    out = [
        "// @generated by scripts/registry.py from the `#[pass]`es under src/: do not edit.",
        "",
        "impl crate::Passes {",
        "    /// Every pass this crate implements and its features compile in.",
        "    pub fn upstream() -> Self {",
        "        let mut p = Self::new();",
        "        p.with(Self::add_upstream);",
        "        p",
        "    }",
        "",
        "    /// Registers every pass this crate implements and its features compile in.",
        "    pub fn add_upstream(&mut self) {",
        "        let p = self;",
    ]
    for file, name, ty, cfgs in rows:
        c = cfg(cfgs)
        if c:
            out.append(f"        #[cfg({c})]")
        out.append(f"        p.register::<crate::{ty}>(); // {name}")
    out += ["    }", "}", ""]
    return "\n".join(out), len(rows)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="fail if src/registry.gen.rs is out of date")
    text, n = render()
    if ap.parse_args().check:
        if not OUT.exists() or OUT.read_text() != text:
            sys.exit("src/registry.gen.rs is out of date: run scripts/registry.py")
        return
    OUT.write_text(text)
    print(f"{OUT.relative_to(ROOT)}: {n} passes")


if __name__ == "__main__":
    main()
