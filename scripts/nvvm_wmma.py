#!/usr/bin/env python3
"""Generates src/patterns/gpu/wmma_nvvm.gen.rs: the NVVM WMMA ops' valid shapes and types
(`WMMALoadOp` / `WMMAStoreOp` / `WMMAMmaOp::getIntrinsicID` and the `infer*Dimension`
helpers), read off mlir-tblgen's NVVMOps.h.inc of LLVM 22.1.8."""
import re, sys
from pathlib import Path

src = Path(sys.argv[1] if len(sys.argv) > 1 else "/usr/lib/llvm-22/include/mlir/Dialect/LLVMIR/NVVMOps.h.inc").read_text()

def body(cls, fn):
    start = src.index(f"\nclass {cls} ")
    i = src.index(fn, start)
    return src[i:src.index("return 0;}", i)]

def cap(s):
    return s[0].upper() + s[1:]

rows = lambda pat, text: re.findall(pat, text)
out = ["// @generated by scripts/nvvm_wmma.py from NVVMOps.h.inc (LLVM 22.1.8); do not edit.", "",
       "use super::wmma_to_nvvm::{MmaFrag, MmaLayout, MmaType};", ""]

load = rows(r'layout == "(\w+)" && m == (\d+) &&\s+n == (\d+) && k == (\d+) && "(\w+)" == eltype && frag == "(\w+)"', body("WMMALoadOp", "getIntrinsicID"))
out.append(f"/// `WMMALoadOp::getIntrinsicID` != 0: layout, m, n, k, element type, fragment.")
out.append(f"pub const LOAD: [(MmaLayout, i64, i64, i64, MmaType, MmaFrag); {len(load)}] = [")
out += [f"    (MmaLayout::{cap(l)}, {m}, {n}, {k}, MmaType::{cap(e)}, MmaFrag::{cap(f)})," for l, m, n, k, e, f in load] + ["];", ""]

store = rows(r'layout == "(\w+)" && m == (\d+) &&\s+n == (\d+) && k == (\d+) && "(\w+)" == eltype\)', body("WMMAStoreOp", "getIntrinsicID"))
out.append(f"/// `WMMAStoreOp::getIntrinsicID` != 0.")
out.append(f"pub const STORE: [(MmaLayout, i64, i64, i64, MmaType); {len(store)}] = [")
out += [f"    (MmaLayout::{cap(l)}, {m}, {n}, {k}, MmaType::{cap(e)})," for l, m, n, k, e in store] + ["];", ""]

mma = rows(r'layoutA == "(\w+)" && layoutB == "(\w+)" &&\s+m == (\d+) && n == (\d+) && k == (\d+)\s+&& "(\w+)" == eltypeA && "(\w+)" == eltypeB', body("WMMAMmaOp", "getIntrinsicID"))
out.append(f"/// `WMMAMmaOp::getIntrinsicID` != 0: layouts, m, n, k, source and destination types.")
out.append(f"pub const MMA: [(MmaLayout, MmaLayout, i64, i64, i64, MmaType, MmaType); {len(mma)}] = [")
out += [f"    (MmaLayout::{cap(a)}, MmaLayout::{cap(b)}, {m}, {n}, {k}, MmaType::{cap(x)}, MmaType::{cap(y)})," for a, b, m, n, k, x, y in mma] + ["];", ""]

for name, cls, fn, x, y in [("LOAD_INFER_N", "WMMALoadOp", "inferNDimension", "m", "k"), ("LOAD_INFER_M", "WMMALoadOp", "inferMDimension", "n", "k"),
                            ("LOAD_INFER_K", "WMMALoadOp", "inferKDimension", "m", "n"), ("STORE_INFER_K", "WMMAStoreOp", "inferKDimension", "m", "n")]:
    r = rows(rf'if \({x} == (\d+) && {y} == (\d+) && "(\w+)" == eltype\)\s+return (\d+);', body(cls, fn))
    out.append(f"/// `{cls}::{fn}`: {x}, {y}, element type, the dimension.")
    out.append(f"pub const {name}: [(i64, i64, MmaType, i64); {len(r)}] = [")
    out += [f"    ({a}, {b}, MmaType::{cap(e)}, {v})," for a, b, e, v in r] + ["];", ""]

Path(__file__).resolve().parent.parent.joinpath("src/patterns/gpu/wmma_nvvm.gen.rs").write_text("\n".join(out))
print(len(load), len(store), len(mma))
