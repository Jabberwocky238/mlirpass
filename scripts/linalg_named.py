#!/usr/bin/env python3
"""Generates src/dialects/linalg_named.gen.rs from llvm-project 22.1.8's OpDSL ops
(mlir/include/mlir/Dialect/Linalg/IR/LinalgNamedStructuredOps.yaml), as mlir-linalg-ods-yaml-gen
reads it for `getIndexingMaps` / `getIteratorTypesArray`:

* each op's iterator types (none: rank polymorphic, the maps follow the operands' ranks);
* its `static_indexing_maps` as written;
* its index attributes (`strides`, `dilations`): the symbols each element binds and the defaults.

    python3 scripts/linalg_named.py --llvm $LLVM
"""

import argparse
import re
from pathlib import Path


def documents(text: str):
    """The `--- !LinalgOpConfig` documents, each as its lines with wrapped values joined."""
    for doc in text.split("--- !LinalgOpConfig")[1:]:
        lines = []
        for line in doc.splitlines():
            # A wrapped `affine_map<...>` continues on deeper-indented lines until `>` balances.
            if lines and lines[-1].count("<") > lines[-1].count(">") - lines[-1].count("->"):
                lines[-1] += " " + line.strip()
            else:
                lines.append(line)
        yield lines


def parse(lines):
    """name, iterator types, static maps, index attributes of one op."""
    name = next(l.split(":", 1)[1].strip() for l in lines if l.startswith("  name:"))
    iterators, maps, attrs, section, arg = [], [], [], None, None
    for l in lines:
        s = l.strip()
        if s.startswith("iterator_types:"):
            section = "it"
        elif s.startswith("static_indexing_maps:"):
            section = "maps"
        elif s.startswith("default_indices:"):
            section = "defaults"
        elif s == "- !LinalgOperandDefConfig":
            section, arg = "arg", {}
        elif section == "it" and s.startswith("- "):
            iterators.append(s[2:])
        elif section == "maps" and s.startswith("- "):
            maps.append(re.sub(r"\s+", " ", s[2:]))
        elif section == "defaults" and s.startswith("- "):
            arg["defaults"].append(int(s[2:]))
        elif section in ("arg", "defaults") and ":" in s and not s.startswith("- "):
            k, v = (x.strip() for x in s.split(":", 1))
            if k in ("name", "kind", "index_attr_map"):
                arg[k] = v
                if k == "kind" and v == "index_attr":
                    arg["defaults"] = []
                    attrs.append(arg)
            if section == "defaults":
                section = "arg"
        elif not l.startswith("    ") and not l.startswith("  - "):
            section = None if section not in ("arg", "defaults") else section
    return name, iterators, maps, attrs


def symbols(index_attr_map: str):
    """The symbol each result of `affine_map<()[s..] -> (s2, s6)>` is."""
    results = index_attr_map.rsplit("->", 1)[1].strip().rstrip(">").strip("() ")
    return [int(r.strip()[1:]) for r in results.split(",")]


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--llvm", required=True, help="llvm-project checkout at llvmorg-22.1.8")
    ap.add_argument("-o", default=str(Path(__file__).resolve().parent.parent / "src" / "dialects" / "linalg_named.gen.rs"))
    opts = ap.parse_args()
    yaml = Path(opts.llvm) / "mlir/include/mlir/Dialect/Linalg/IR/LinalgNamedStructuredOps.yaml"
    out = ["// Generated by scripts/linalg_named.py from llvm-project 22.1.8's LinalgNamedStructuredOps.yaml; do not edit.",
           "", "use super::{IndexAttr, OpDsl};", "", "/// Every OpDSL op, by name.", "pub const OPDSL: &[OpDsl<'_>] = &["]
    for lines in documents(yaml.read_text()):
        name, iterators, maps, attrs = parse(lines)
        red = ", ".join("true" if i == "reduction" else "false" for i in iterators)
        ms = ", ".join(f'"{m}"' for m in maps)
        ats = ", ".join(
            f'IndexAttr {{ name: "{a["name"]}", syms: &[{", ".join(map(str, symbols(a["index_attr_map"])))}], defaults: &[{", ".join(map(str, a["defaults"]))}] }}'
            for a in attrs)
        out.append(f'    OpDsl {{ name: "linalg.{name}", reductions: &[{red}], maps: &[{ms}], attrs: &[{ats}] }},')
    out.append("];")
    Path(opts.o).write_text("\n".join(out) + "\n")
    print(f"{opts.o}: {len(out) - 7} ops")


if __name__ == "__main__":
    main()
