"""Writes src/patterns/nir/algebraic.gen.rs: Mesa's nir_opt_algebraic rules, as nir_algebraic.py parses them.

    python3 scripts/nir_algebraic.py MESA/src/compiler/nir MESA_VERSION

Mesa's own parser reads the rules (nir_algebraic.py, with nir_opcodes.py beside it; mako, which it only renders C
with, is not needed); each rule is written as it parsed: the search and the replace trees, every node's bit size in
Mesa's encoding (n: n bits; -(i + 1): variable i's; 0: the search's), the conditions as Mesa wrote them (the rule's
C condition, an expression's or a variable's predicate) for the engine to evaluate. The tables are Mesa's passes:
nir_opt_algebraic, nir_opt_algebraic_before_ffma, nir_opt_algebraic_late, nir_opt_algebraic_distribute_src_mods.
"""
import struct
import sys
import types
from pathlib import Path


class Mesa:
    """Mesa's rule lists, read with Mesa's parser"""

    # the lists nir_opt_algebraic.py renders, with the pass each is
    TABLES = [
        ("OPTIMIZATIONS", "optimizations", "nir_opt_algebraic"),
        ("BEFORE_FFMA", "before_ffma_optimizations", "nir_opt_algebraic_before_ffma"),
        ("LATE", "late_optimizations", "nir_opt_algebraic_late"),
        ("DISTRIBUTE_SRC_MODS", "distribute_src_mods", "nir_opt_algebraic_distribute_src_mods"),
    ]
    MAIN = "parser = argparse.ArgumentParser()"

    def __init__(self, nir_dir):
        sys.path.insert(0, str(nir_dir))
        mako = types.ModuleType("mako")
        template = types.ModuleType("mako.template")
        template.Template = lambda *a, **k: None
        mako.template = template
        sys.modules["mako"], sys.modules["mako.template"] = mako, template
        import nir_algebraic

        self.na = nir_algebraic
        source = Path(nir_dir, "nir_opt_algebraic.py").read_text()
        self.ns = {"__name__": "nir_opt_algebraic_rules"}
        exec(compile(source.split(Mesa.MAIN)[0], "nir_opt_algebraic.py", "exec"), self.ns)

    def passes(self):
        for rust, rules, name in Mesa.TABLES:
            yield rust, name, self.na.AlgebraicPass(name, self.ns[rules])


class Writer:
    """Rust for the parsed rules"""

    def __init__(self, mesa):
        self.na = mesa.na

    @staticmethod
    def string(s):
        return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'

    @staticmethod
    def var_cond(algebraic_pass, index):
        if index < 0:
            return "None"
        conds = {i: c for c, i in algebraic_pass.variable_cond.items()}
        return f"Some({Writer.string(conds[index].strip('()'))})"

    def constant(self, v):
        value = v.value
        if isinstance(value, bool):
            return f"NirConst::Bool({str(value).lower()})"
        if isinstance(value, float):
            bits = struct.unpack("<Q", struct.pack("<d", value))[0]
            return f"NirConst::Float({bits:#x})"
        return f"NirConst::Int({int(value)})"

    def node(self, v, algebraic_pass):
        bits = v.c_bit_size
        if isinstance(v, self.na.Expression):
            srcs = ", ".join(self.node(s, algebraic_pass) for s in v.sources)
            cond = f"Some({Writer.string(v.cond)})" if v.cond else "None"
            swizzle = "None" if v.swizzle < 0 else f"Some({v.swizzle})"
            flags = f"inexact: {str(v.inexact).lower()}, exact: {str(v.exact).lower()}, ignore_exact: {str(v.ignore_exact).lower()}"
            fp = f"nsz: {str(v.nsz).lower()}, nnan: {str(v.nnan).lower()}, ninf: {str(v.ninf).lower()}, contract: {str(v.contract).lower()}"
            return f'NirPat::Expr {{ op: "nir.{v.opcode}", bits: {bits}, {flags}, {fp}, cond: {cond}, swizzle: {swizzle}, srcs: &[{srcs}] }}'
        if isinstance(v, self.na.Variable):
            ty = {None: "None", "float": "Some(NirBase::Float)", "int": "Some(NirBase::Int)", "uint": "Some(NirBase::Uint)", "bool": "Some(NirBase::Bool)"}[v.required_type]
            swiz = "None" if v.swiz is None else f"Some({Writer.string(v.swiz[1:])})"
            return f"NirPat::Var {{ index: {v.index}, constant: {str(v.is_constant).lower()}, bits: {bits}, ty: {ty}, cond: {Writer.var_cond(algebraic_pass, v.cond_index)}, swizzle: {swiz} }}"
        if isinstance(v, self.na.Constant):
            return f"NirPat::Const {{ value: {self.constant(v)}, bits: {bits} }}"
        raise TypeError(f"a {type(v).__name__} in a rule")

    def rust(self, mesa, version):
        out = [
            f"// Generated by scripts/nir_algebraic.py from Mesa {version}'s src/compiler/nir/nir_opt_algebraic.py: do not edit.",
            "",
            "use mlirformat::nir::NirBase;",
            "",
            "use super::{NirConst, NirPat, NirRule, NirRules};",
            "",
            "impl NirRules {",
        ]
        for rust, name, algebraic_pass in mesa.passes():
            out += [f"    /// {name}: {len(algebraic_pass.xforms)} rules, in Mesa's order", f"    pub const {rust}: &[NirRule<'_>] = &["]
            for x in algebraic_pass.xforms:
                search, replace = self.node(x.search, algebraic_pass), self.node(x.replace, algebraic_pass)
                out.append(f"        NirRule {{ search: {search}, replace: {replace}, condition: {Writer.string(x.condition)} }},")
            out += ["    ];", ""]
        out[-1:] = ["}", ""]
        return "\n".join(out)


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    mesa = Mesa(sys.argv[1])
    Path(__file__).resolve().parent.parent.joinpath("src/patterns/nir/algebraic.gen.rs").write_text(Writer(mesa).rust(mesa, sys.argv[2]))
